// Usage (from the repo root): node scripts/images/photos.cjs [scripts/images/photos.json]
//
// The site's photographs are Romandy CTO event photos (full resolution originals, 7008x4672).
// For every entry in photos.json this script:
//   1. reads the original from its absolute path (the originals live on David's machine, not in git),
//   2. applies the EXIF orientation, resizes to at most 2400px on the long edge,
//      applies a light shared grade (a touch of warmth toward the cream palette, skin tones kept natural),
//      strips all metadata and writes public/images/site/<id>.webp (quality 78),
//   3. writes a 16px blur placeholder,
//   4. for entries with "og", writes a 1200x630 JPEG crop to public/images/site/<og>.jpg,
//      cropped with the same object-position semantics as <Frame position>.
// Then it regenerates src/lib/images.ts. Do not edit images.ts by hand.
const path = require("path"), fs = require("fs");
const sharp = require(require.resolve("sharp", { paths: [process.cwd()] }));

const R = process.cwd();
const manifestPath = process.argv[2] || path.join(__dirname, "photos.json");
const manifest = JSON.parse(fs.readFileSync(manifestPath, "utf8"));
const outDir = path.join(R, "public/images/site");
fs.mkdirSync(outDir, { recursive: true });

const MAX = 2400;
const QUALITY = 78;
const OG = { width: 1200, height: 630 };
const grade = { warmth: 0.025, saturation: 0.97, brightness: 1.01, ...(manifest.grade || {}) };

/** "45% 50%" -> [0.45, 0.5] */
function parsePosition(pos = "50% 50%") {
  const [x, y = "50%"] = String(pos).trim().split(/\s+/);
  const pct = (v) => Math.min(1, Math.max(0, parseFloat(v) / 100));
  return [pct(x), pct(y)];
}

/** Light, consistent grade: warm the highlights a touch (red up, blue down), ease saturation. */
function graded(img) {
  const w = grade.warmth;
  return img
    .recomb([
      [1 + w, 0, 0],
      [0, 1 + w / 5, 0],
      [0, 0, 1 - w * 1.2],
    ])
    .modulate({ saturation: grade.saturation, brightness: grade.brightness });
}

(async () => {
  const entries = [];
  const ogs = {};
  for (const p of manifest.photos) {
    if (!fs.existsSync(p.original)) throw new Error(`Missing original for ${p.id}: ${p.original}`);

    // Oriented, resized, graded master in memory (raw pixels, no metadata).
    const { data, info } = await graded(
      sharp(p.original).rotate().resize(MAX, MAX, { fit: "inside", withoutEnlargement: true }),
    )
      .raw()
      .toBuffer({ resolveWithObject: true });
    const master = () => sharp(data, { raw: { width: info.width, height: info.height, channels: info.channels } });

    const webp = await master().webp({ quality: QUALITY, effort: 6, smartSubsample: true }).toBuffer();
    fs.writeFileSync(path.join(outDir, p.id + ".webp"), webp);

    const blur = await master().resize(16).webp({ quality: 40 }).toBuffer();

    if (p.og) {
      const [px, py] = parsePosition(p.position);
      const scale = Math.max(OG.width / info.width, OG.height / info.height);
      const w = Math.round(info.width * scale), h = Math.round(info.height * scale);
      const left = Math.round((w - OG.width) * px), top = Math.round((h - OG.height) * py);
      const ogBuf = await master()
        .resize(w, h)
        .extract({ left, top, width: OG.width, height: OG.height })
        .jpeg({ quality: 80, mozjpeg: true })
        .toBuffer();
      fs.writeFileSync(path.join(outDir, p.og + ".jpg"), ogBuf);
      ogs[p.og] = ogBuf.length;
    }

    entries.push({ ...p, w: info.width, h: info.height, size: webp.length, blur: "data:image/webp;base64," + blur.toString("base64") });
    console.log(p.id, info.width + "x" + info.height, (webp.length / 1024).toFixed(0) + "KB");
  }

  const lines = entries.map(
    (e) => `  ${JSON.stringify(e.id)}: {
    src: "/images/site/${e.id}.webp",
    width: ${e.w},
    height: ${e.h},
    alt: ${JSON.stringify(e.alt)},
    position: ${JSON.stringify(e.position || "50% 50%")},
    blurDataURL: "${e.blur}",
  },`,
  );
  const ts = `// Generated by scripts/images/photos.cjs from scripts/images/photos.json. Do not edit by hand.
// Romandy CTO event photography. These are not Haystack or FDE Club events: never caption them as such.
export type ImageEntry = {
  readonly src: \`/images/site/\${string}.webp\`
  readonly width: number
  readonly height: number
  readonly alt: string
  /** Default CSS object-position (focal point) for this photo. */
  readonly position?: string
  readonly blurDataURL: \`data:image/webp;base64,\${string}\`
}

export const IMG = {
${lines.join("\n")}
} as const satisfies Record<string, ImageEntry>

export type ImageId = keyof typeof IMG

/** 1200x630 photo crops behind the Open Graph images (paths relative to the repo root). */
export const OG_IMAGES = {
${Object.keys(ogs).map((k) => `  ${JSON.stringify(k.replace(/^og-/, ""))}: "public/images/site/${k}.jpg",`).join("\n")}
} as const
export type OgVariant = keyof typeof OG_IMAGES
export const OG_IMAGE_PATH = OG_IMAGES.default
`;
  fs.writeFileSync(path.join(R, "src/lib/images.ts"), ts);
  for (const [k, size] of Object.entries(ogs)) console.log(k + ".jpg", (size / 1024).toFixed(0) + "KB");
})().catch((e) => {
  console.error(e);
  process.exit(1);
});
