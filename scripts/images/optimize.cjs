// Usage (from the repo root): node scripts/images/optimize.cjs scripts/images/selection.json
// Reads the chosen raw PNGs from scripts/images/raw/ (git-ignored), writes WebP files to
// public/images/site/, the OG crop og-needle.jpg, and regenerates src/lib/images.ts.
// selection.json maps each image id to its raw file name.
const path = require("path"), fs = require("fs");
const sharp = require(require.resolve("sharp", { paths: [process.cwd()] }));
const S = __dirname, R = process.cwd();
const sel = JSON.parse(fs.readFileSync(process.argv[2], "utf8"));
const prompts = JSON.parse(fs.readFileSync(path.join(S, "prompts.json"), "utf8"));
const outDir = path.join(R, "public/images/site"); fs.mkdirSync(outDir, { recursive: true });
(async () => {
  const entries = [];
  for (const id of Object.keys(prompts)) {
    const raw = path.join(S, "raw", sel[id]);
    const meta = await sharp(raw).metadata();
    const scale = Math.min(1, 2000 / Math.max(meta.width, meta.height));
    const w = Math.round(meta.width * scale), h = Math.round(meta.height * scale);
    const budget = id === "hero-needle" ? 180 * 1024 : 220 * 1024;
    let buf, q;
    for (q of [78, 72, 66, 60]) {
      buf = await sharp(raw).resize(w, h).webp({ quality: q, effort: 6 }).toBuffer();
      if (buf.length <= budget) break;
    }
    fs.writeFileSync(path.join(outDir, id + ".webp"), buf);
    const blur = await sharp(raw).resize(16).webp({ quality: 40 }).toBuffer();
    entries.push({ id, w, h, q, size: buf.length, blur: "data:image/webp;base64," + blur.toString("base64"), alt: prompts[id].alt });
    if (id === "hero-needle") {
      const og = sharp(raw).resize(540, 630, { fit: "cover", position: sel.ogPosition || "centre" }).jpeg({ quality: 80, mozjpeg: true });
      await og.toFile(path.join(outDir, "og-needle.jpg"));
    }
  }
  const lines = entries.map(e => `  ${JSON.stringify(e.id)}: {\n    src: "/images/site/${e.id}.webp",\n    width: ${e.w},\n    height: ${e.h},\n    alt: ${JSON.stringify(e.alt)},\n    blurDataURL: "${e.blur}",\n  },`);
  const ts = `// Generated by the images pipeline (gpt-image-2.5, optimised with sharp). Do not edit by hand.
export type ImageEntry = {
  readonly src: \`/images/site/\${string}.webp\`
  readonly width: number
  readonly height: number
  readonly alt: string
  readonly blurDataURL: \`data:image/webp;base64,\${string}\`
}

export const IMG = {
${lines.join("\n")}
} as const satisfies Record<string, ImageEntry>

export type ImageId = keyof typeof IMG
export const OG_IMAGE_PATH = "public/images/site/og-needle.jpg"
`;
  fs.writeFileSync(path.join(R, "src/lib/images.ts"), ts);
  for (const e of entries) console.log(e.id, e.w + "x" + e.h, "q" + e.q, (e.size / 1024).toFixed(0) + "KB");
  console.log("og", (fs.statSync(path.join(outDir, "og-needle.jpg")).size / 1024).toFixed(0) + "KB");
})().catch(e => { console.error(e); process.exit(1); });
